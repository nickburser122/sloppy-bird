const FUR = '#8a5a3a';
const BELLY = '#e8cfa8';
const BOARD = '#2fc7b8';
const DARK = '#2a1a12';

export const otterColors = [FUR, BELLY, BOARD, '#ffffff'];

export function drawOtter(ctx, x, y, st) {
  const cx = x + 20;
  const under = st.depth > 8;
  ctx.save();
  ctx.translate(cx, y);
  let ang = st.air ? Math.max(-0.5, Math.min(0.5, st.vy / 1800)) : Math.atan(st.slope || 0);
  if (st.hold && !st.air) ang += 0.35;
  ctx.rotate(ang);
  ctx.globalAlpha = under ? 0.8 : 1;
  ctx.fillStyle = BOARD;
  ctx.strokeStyle = '#0f6e66';
  ctx.lineWidth = 2;
  ctx.beginPath();
  ctx.roundRect(-30, 4, 60, 9, 5);
  ctx.fill();
  ctx.stroke();
  ctx.fillStyle = FUR;
  ctx.beginPath();
  ctx.ellipse(-6, -4, 14, 9, 0, 0, Math.PI * 2);
  ctx.fill();
  ctx.fillStyle = BELLY;
  ctx.beginPath();
  ctx.ellipse(-4, 0, 9, 4.5, 0, 0, Math.PI * 2);
  ctx.fill();
  ctx.strokeStyle = FUR;
  ctx.lineWidth = 5;
  ctx.lineCap = 'round';
  ctx.beginPath();
  ctx.moveTo(-18, -2);
  ctx.quadraticCurveTo(-30, -2 + Math.sin(st.t * 10) * 3, -34, 3);
  ctx.stroke();
  ctx.fillStyle = FUR;
  ctx.beginPath();
  ctx.arc(10, -9, 8, 0, Math.PI * 2);
  ctx.fill();
  ctx.beginPath();
  ctx.arc(6, -16, 3, 0, Math.PI * 2);
  ctx.arc(13, -17, 3, 0, Math.PI * 2);
  ctx.fill();
  ctx.fillStyle = BELLY;
  ctx.beginPath();
  ctx.ellipse(15, -6, 5, 4, 0, 0, Math.PI * 2);
  ctx.fill();
  ctx.fillStyle = DARK;
  ctx.beginPath();
  ctx.arc(18, -8, 1.8, 0, Math.PI * 2);
  ctx.arc(10, -11, 1.6, 0, Math.PI * 2);
  ctx.fill();
  ctx.strokeStyle = 'rgba(255,255,255,0.7)';
  ctx.lineWidth = 1;
  ctx.beginPath();
  ctx.moveTo(18, -5);
  ctx.lineTo(26, -7);
  ctx.moveTo(18, -4);
  ctx.lineTo(26, -3);
  ctx.stroke();
  ctx.restore();
}
