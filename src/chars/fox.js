const BODY = '#f2802e';
const DARK = '#3a1f1a';
const CREAM = '#ffe9cf';

export const foxColors = [BODY, CREAM, DARK];

export function drawFox(ctx, x, y, st) {
  const phase = st.t * 18;
  const sq = st.landT > 0 ? st.landT / 0.12 : 0;
  const stretch = st.grounded ? 0 : Math.max(-0.12, Math.min(0.18, -st.vy / 5000));
  ctx.save();
  ctx.translate(x + 20, y);
  ctx.scale(1 + sq * 0.2 - stretch * 0.5, 1 - sq * 0.2 + stretch);
  const wag = Math.sin(phase * 0.6) * 4;
  ctx.fillStyle = BODY;
  ctx.beginPath();
  ctx.moveTo(-10, -20);
  ctx.quadraticCurveTo(-30, -30 + wag, -34, -14 + wag);
  ctx.quadraticCurveTo(-22, -16, -8, -12);
  ctx.closePath();
  ctx.fill();
  ctx.fillStyle = CREAM;
  ctx.beginPath();
  ctx.moveTo(-28, -21 + wag * 0.8);
  ctx.quadraticCurveTo(-34, -22 + wag, -34, -14 + wag);
  ctx.quadraticCurveTo(-30, -15 + wag, -26, -17 + wag);
  ctx.closePath();
  ctx.fill();
  ctx.strokeStyle = DARK;
  ctx.lineWidth = 4;
  ctx.lineCap = 'round';
  const swing = st.grounded ? Math.sin(phase) * 9 : 0;
  const tuck = st.grounded ? 0 : -5;
  ctx.beginPath();
  ctx.moveTo(-7, -10);
  ctx.lineTo(-7 + swing, -1 + tuck);
  ctx.moveTo(8, -10);
  ctx.lineTo(8 - swing, -1 + tuck);
  ctx.stroke();
  ctx.fillStyle = BODY;
  ctx.beginPath();
  ctx.ellipse(0, -18, 15, 9, 0, 0, Math.PI * 2);
  ctx.fill();
  ctx.fillStyle = CREAM;
  ctx.beginPath();
  ctx.ellipse(2, -14, 10, 4, 0, 0, Math.PI * 2);
  ctx.fill();
  ctx.fillStyle = BODY;
  ctx.beginPath();
  ctx.ellipse(13, -25, 9, 8, 0, 0, Math.PI * 2);
  ctx.fill();
  ctx.beginPath();
  ctx.moveTo(8, -30);
  ctx.lineTo(10, -39);
  ctx.lineTo(15, -31);
  ctx.moveTo(14, -31);
  ctx.lineTo(19, -38);
  ctx.lineTo(20, -29);
  ctx.fill();
  ctx.fillStyle = CREAM;
  ctx.beginPath();
  ctx.moveTo(14, -21);
  ctx.lineTo(24, -23);
  ctx.lineTo(17, -17);
  ctx.closePath();
  ctx.fill();
  ctx.fillStyle = DARK;
  ctx.beginPath();
  ctx.arc(24, -23, 2, 0, Math.PI * 2);
  ctx.arc(15, -27, 1.8, 0, Math.PI * 2);
  ctx.fill();
  ctx.restore();
}
